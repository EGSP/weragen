// Описание процессов разработки для pm2.
//
// Каждый процесс запускается под собственным именем, поэтому их видно списком (`npm run ps`),
// журнал каждого читается отдельно (`npm run logs:server` и далее), и перезапустить можно
// любой, не трогая остальные.
//
// Скрипты указывают прямо на файлы запуска, а не на npm: pm2 под Windows не умеет исполнять
// `npm.cmd` как модуль Node.
//
// Сборка и запуск сервера разделены намеренно. Режим наблюдения Nest порождает приложение
// дочерним процессом; pm2 останавливает только родителя, дочерний продолжает держать порт,
// и перезапуск проходит лишь со второй попытки. Здесь pm2 управляет самим приложением
// напрямую, а перекомпиляцию ведёт отдельный процесс.
module.exports = {
    apps: [
        {
            name: 'weragen-build',
            cwd: './server',
            script: '../node_modules/tsc-watch/dist/lib/tsc-watch.js',
            // Перезапуск приложения делается по фактической записи файлов сборки, а не по
            // каждой успешной компиляции. Различие существенно: компилятор пересобирает
            // программу и тогда, когда её содержимое не изменилось, и по `--onSuccess`
            // перезапуск шёл на каждую такую холостую пересборку. Наблюдение pm2 за каталогом
            // сборки здесь тоже не годится — компилятор пишет файлы по одному, и получается
            // залп перезапусков.
            //
            // Задержка `--onEmitDebounceMs` сворачивает серию сборок в один перезапуск: правка
            // нескольких файлов подряд, сборка пакетов рабочей области и `prisma generate`
            // иначе дают столько циклов остановки и запуска, сколько было записей.
            //
            // При ошибке компиляции перезапуска нет вовсе — сервер продолжает работать на
            // прежней сборке, а ошибка видна в этом журнале.
            //
            // Ключ `--signalEmittedFiles` обязателен: записанные файлы tsc-watch различает по
            // строкам «TSFILE:» в выводе компилятора, а выводить их компилятор начинает только
            // по этому ключу. Без него `--onEmit` не срабатывает ни разу. В журнал строки
            // «TSFILE:» при этом не попадают — их печатает другой ключ, `--listEmittedFiles`.
            args:
                '--noClear --signalEmittedFiles ' +
                '--onEmit "node ../scripts/restart-server.mjs" --onEmitDebounceMs 1500',
            autorestart: true,
            watch: false,
            out_file: '../logs/build.log',
            error_file: '../logs/build.error.log',
            time: true,
        },
        {
            name: 'weragen-server',
            cwd: './server',
            script: 'dist/main.js',
            autorestart: true,
            // Собственного наблюдения за файлами нет: перезапуск инициирует сборка.
            watch: false,
            // Завершение по сообщению, а не по сигналу. В Windows сигнал, посланный процессу
            // извне, прекращает работу немедленно, и приложение не успевает закрыть слушающий
            // сокет — следующий запуск получал занятый порт. Сообщение «shutdown» приходит по
            // каналу IPC, и приложение завершается само (обработчик в server/src/main.ts).
            shutdown_with_message: true,
            // Предел ожидания добровольного завершения; после него процесс прекращается
            // принудительно, то есть худший случай совпадает с прежним поведением.
            kill_timeout: 5000,
            max_memory_restart: '512M',
            out_file: '../logs/server.log',
            error_file: '../logs/server.error.log',
            time: true,
        },
        {
            name: 'weragen-web',
            cwd: './web-client',
            // Vite обновляет модули в браузере сам, поэтому перезапуск процесса нужен только
            // при изменении его собственной конфигурации.
            script: '../node_modules/vite/bin/vite.js',
            autorestart: true,
            watch: false,
            out_file: '../logs/web.log',
            error_file: '../logs/web.error.log',
            time: true,
        },
    ],
};
