import { ASK_USER, ATTEMPT_COMPLETION, type CompletionMode } from './terminal.js';

/**
 * Системный промпт агента.
 *
 * Правило «сначала вызовы инструментов, потом ответ» здесь не украшение: без него модель
 * порождает выводы в том же сообщении, где запрашивает данные для них, и эти выводы
 * оказываются вымышленными — результатов вызовов она ещё не получила.
 *
 * Запрет на изображения тоже вызван наблюдением: построив график, модель добавляла в ответ
 * разметку изображения со ссылкой на несуществующий файл. Предписание сформулировано общим,
 * а не привязанным к одному инструменту, потому что тот же образец порождает ссылки на файлы
 * и вставки данных прямо в текст.
 */
const COMMON = [
    'Ты — рабочий агент платформы weragen. У тебя есть инструменты; чтобы узнать факт, вызывай',
    'инструмент, а не предполагай. Простую арифметику считай сам, инструмент для неё не нужен.',
    'Не выдумывай данные. Если инструмент вернул ошибку — прочитай её текст и исправь вызов,',
    'а не повторяй тот же самый.',
    'Сначала вызовы инструментов, потом ответ: не пиши выводы в том же сообщении, где',
    'запрашиваешь данные для них.',
    'Отвечай по-русски и кратко.',
    'Ответ размечай Markdown: списки и таблицы там, где они делают его понятнее.',
    'Изображения в ответе не выводятся: наглядно показать данные можно только вызовом',
    'render_chart. Разметку изображения и ссылки на файлы в текст не вставляй.',
];

/**
 * Указания о завершении различаются по дисциплине. В чат-сессии есть кому задать вопрос, в
 * агентской — нет, и предложить там `ask_user` значило бы дать модели способ остановиться
 * без результата.
 */
const CHAT = [
    `Закончив, вызови ${ATTEMPT_COMPLETION} и передай итоговый ответ его аргументом.`,
    `Если продолжать без ответа человека нельзя — вызови ${ASK_USER}, а не задавай вопрос`,
    'обычным текстом: заданный текстом вопрос останется без ответа.',
];

const TASK = [
    'Ты выполняешь задачу, поставленную программой. Человека рядом нет: спросить не у кого,',
    'уточнений не будет, недостающее восполняй разумным допущением и указывай его в ответе.',
    `Закончив, обязательно вызови ${ATTEMPT_COMPLETION} и передай итог его аргументом —`,
    'ровно то, что нужно вызывающей стороне, без вступлений и пояснений о своей работе.',
];

export function systemPrompt(mode: CompletionMode): string {
    return [...COMMON, ...(mode === 'chat' ? CHAT : TASK)].join(' ');
}

/**
 * Дополняет промпт секциями, которые платформа получает извне: сейчас это текстовые
 * инструкции подключённых серверов MCP.
 *
 * Секции ставятся после основных указаний, а не перед ними: указания платформы о том, как
 * завершать ход и как обходиться с отказами инструментов, не должны вытесняться текстом,
 * который пишет автор внешнего сервера.
 */
export function withSections(base: string, sections: readonly string[]): string {
    const meaningful = sections.filter((section) => section.trim() !== '');
    return meaningful.length === 0 ? base : [base, ...meaningful].join('\n\n');
}

/** Промпт чат-сессии. Оставлен отдельным именем: на него ссылается прежний код. */
export const SYSTEM_PROMPT = systemPrompt('chat');
